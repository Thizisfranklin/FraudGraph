"""Run prespecified complexity and label-delay checks (exploratory research).

Generates a self-contained, interactive HTML research report (not a deployment).
The transaction input and original predictions are generated by the original
FraudGraph pipeline. There are NO fabricated model improvement claims.
"""
import argparse
import json
from pathlib import Path
import sys

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from fraudgraph.data import LOCAL
from fraudgraph.graph import GRAPH_FEATURES
from fraudgraph.robustness import (
    CAPACITY_PRESETS, validation_backtest, replay_selected,
)


def run(root, include_posthoc_test=False, label_lags=(2, 4, 6)):
    source = root / "data/processed/transactions.parquet"
    if not source.exists():
        raise FileNotFoundError(
            f"Missing {source}. First run python -m fraudgraph.pipeline --download"
        )
    frame = pd.read_parquet(source)
    frame["Time step"] = frame["Time step"].astype(int)
    out = root / "reports/exploratory"
    out.mkdir(parents=True, exist_ok=True)
    columns = LOCAL + GRAPH_FEATURES

    folds, budgets, leaderboard, selected = validation_backtest(
        frame, columns, label_lags=tuple(label_lags)
    )
    folds.to_csv(out / "regularization_validation_folds.csv", index=False)
    leaderboard.to_csv(out / "regularization_validation_leaderboard.csv", index=False)
    selected.to_csv(out / "regularization_selected_per_lag.csv", index=False)

    # Preserve just the selected candidate's analyst-budget diagnostics in a
    # separate file. Validation decisions were based on AP, NOT capacity.
    keys = selected[["label_lag", "candidate"]]
    selected_budgets = budgets.merge(keys, on=["label_lag", "candidate"], validate="many_to_one")
    selected_budgets.to_csv(out / "capacity_validation.csv", index=False)

    if include_posthoc_test:
        posthoc, future_budget = replay_selected(frame, columns, selected)
        posthoc.to_csv(out / "regularization_posthoc_test.csv", index=False)
        future_budget.to_csv(out / "capacity_posthoc_test.csv", index=False)

    manifest = {
        "study_type": "EXPLORATORY; not fresh external validation",
        "label_lags_scenario": list(label_lags),
        "strategy_candidates": ["frozen", "expanding", "rolling", "recency"],
        "capacity_presets": [vars(p) for p in CAPACITY_PRESETS],
        "validation_target_steps": [35, 37, 39],
        "selection_rule": "max worst-period validation AP, then mean AP, then simpler model",
        "posthoc_test_run": include_posthoc_test,
        "posthoc_steps": list(range(40, 50)) if include_posthoc_test else [],
        "warnings": [
            "Known illicit labels are selectively observed; unknown outcomes are not negatives.",
            "True label-availability timestamps are absent. Delay is a hypothetical scenario.",
            "Training AP is in-sample and not a deployment quality measure.",
            "A train/validation gap can result from drift as well as classical overfitting.",
            "Selection uses a small number of dependent validation periods.",
            "The test period was already used to motivate this research; it is post-hoc.",
            "Scores are not calibrated probabilities and are not evidence of guilt.",
        ],
    }
    (out / "regularization_manifest.json").write_text(
        json.dumps(manifest, indent=2), encoding="utf-8"
    )
    print("\nTemporal robustness leaderboard (first place per assumed lag):")
    print(selected[["label_lag", "candidate", "worst_forward_ap",
                    "mean_forward_ap", "mean_excess_ap_gap"]].to_string(index=False))
    print("Analysis outputs:", out)
    print("Post-hoc replay:", "YES (not pristine test)" if include_posthoc_test else "NO")
    return manifest


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=ROOT)
    parser.add_argument("--label-lags", type=int, nargs="+", default=[2, 4, 6])
    parser.add_argument("--include-posthoc-test", action="store_true")
    args = parser.parse_args()
    run(args.root.resolve(), args.include_posthoc_test, tuple(args.label_lags))


if __name__ == "__main__":
    main()
